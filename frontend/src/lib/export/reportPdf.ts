/*
 * A report as a PDF document, the way Power BI's "Export to PDF" hands over a
 * page: the ministry's seal and the report's name, what it covers (period,
 * filters, scope, when the data was read and by whom), the headline figures,
 * a picture of every chart, the tables and the definitions, with page numbers.
 * jsPDF is loaded only when a document is made.
 */

import type { Snapshot } from './snapshot';

export interface PdfKpi {
  label: string;
  value: string;
  detail?: string | undefined;
}

export interface PdfTable {
  title: string;
  columns: readonly string[];
  rows: readonly (readonly (string | number | null)[])[];
}

export interface PdfReport {
  title: string;
  /** One line under the title, e.g. the workspace and scope. */
  subtitle?: string | undefined;
  /** Label and value pairs: period, filters, scope, data time, generated by. */
  meta: readonly (readonly [string, string])[];
  kpis: readonly PdfKpi[];
  visuals: readonly (Snapshot & { title: string })[];
  tables: readonly PdfTable[];
  notes: readonly string[];
  /** Width in CSS pixels of the page area the visuals came from; visuals under 62% of it go two to a row. */
  layoutWidth?: number | undefined;
  /** The seal as a data URL, or null to leave it out. */
  seal: string | null;
  generatedAt: Date;
}

const PAGE = { width: 210, height: 297, margin: 14 } as const;
const CONTENT = PAGE.width - PAGE.margin * 2;
const INK = [12, 13, 15] as const;
const MUTED = [98, 102, 109] as const;
const HAIRLINE = [228, 230, 233] as const;
const HEAD_FILL = [237, 247, 238] as const;
const BRAND = [69, 186, 80] as const;

function stamp(date: Date): string {
  return new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Africa/Kampala',
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  }).format(date);
}

export async function buildReportPdf(report: PdfReport): Promise<Blob> {
  const [{ jsPDF }, { autoTable }] = await Promise.all([
    import('jspdf'),
    import('jspdf-autotable'),
  ]);
  const doc = new jsPDF({ unit: 'mm', format: 'a4', orientation: 'portrait', compress: true });
  doc.setProperties({
    title: report.title,
    subject: 'CLIMS report',
    author: 'Ministry of Health, Uganda — CLIMS',
    creator: 'CLIMS',
  });
  let y = PAGE.margin;

  const pageWidth = () => doc.internal.pageSize.getWidth();
  const pageHeight = () => doc.internal.pageSize.getHeight();
  const ensure = (height: number) => {
    if (y + height > pageHeight() - PAGE.margin - 8) {
      doc.addPage('a4', pageWidth() > pageHeight() ? 'landscape' : 'portrait');
      y = PAGE.margin;
    }
  };
  const text = (
    value: string,
    x: number,
    size: number,
    options: {
      bold?: boolean;
      color?: readonly number[];
      maxWidth?: number;
      align?: 'left' | 'right' | 'center';
    } = {},
  ) => {
    doc.setFont('helvetica', options.bold ? 'bold' : 'normal');
    doc.setFontSize(size);
    const [r = 0, g = 0, b = 0] = options.color ?? INK;
    doc.setTextColor(r, g, b);
    const lines = doc.splitTextToSize(value, options.maxWidth ?? CONTENT) as string[];
    doc.text(lines, x, y, { align: options.align ?? 'left', baseline: 'top' });
    return lines.length * size * 0.3528 * 1.25;
  };

  // Header: seal, ministry and system, then the report's name.
  const sealSize = 16;
  if (report.seal) doc.addImage(report.seal, 'PNG', PAGE.margin, y, sealSize, sealSize);
  const headerX = PAGE.margin + (report.seal ? sealSize + 4 : 0);
  text('Ministry of Health, Uganda', headerX, 9, { bold: true, maxWidth: CONTENT - 60 });
  y += 4.5;
  text('CLIMS · Condom Logistics Information Management System', headerX, 8, {
    color: MUTED,
    maxWidth: CONTENT - 60,
  });
  y -= 4.5;
  text(`Generated ${stamp(report.generatedAt)}`, PAGE.width - PAGE.margin, 8, {
    color: MUTED,
    align: 'right',
    maxWidth: 60,
  });
  y += sealSize + 3;
  doc.setDrawColor(...BRAND);
  doc.setLineWidth(0.8);
  doc.line(PAGE.margin, y, PAGE.margin + 24, y);
  y += 4;
  y += text(report.title, PAGE.margin, 17, { bold: true });
  if (report.subtitle) y += text(report.subtitle, PAGE.margin, 9.5, { color: MUTED }) + 1;
  y += 2;

  // What the report covers.
  if (report.meta.length > 0) {
    autoTable(doc, {
      startY: y,
      margin: { left: PAGE.margin, right: PAGE.margin },
      theme: 'plain',
      styles: {
        fontSize: 8.5,
        cellPadding: { top: 1, bottom: 1, left: 0, right: 3 },
        textColor: [...INK],
      },
      columnStyles: { 0: { cellWidth: 32, textColor: [...MUTED] } },
      body: report.meta.map(([label, value]) => [label, value]),
    });
    y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 5;
  }

  // Headline figures, three to a row.
  if (report.kpis.length > 0) {
    const perRow = 3;
    const gap = 3;
    const width = (CONTENT - gap * (perRow - 1)) / perRow;
    const height = 19;
    report.kpis.forEach((kpi, index) => {
      const column = index % perRow;
      if (column === 0) ensure(height + gap);
      const x = PAGE.margin + column * (width + gap);
      doc.setDrawColor(...HAIRLINE);
      doc.setLineWidth(0.25);
      doc.roundedRect(x, y, width, height, 1.5, 1.5, 'S');
      const top = y;
      y = top + 2.5;
      text(kpi.label, x + 3, 7.5, { color: MUTED, maxWidth: width - 6 });
      y = top + 7.5;
      text(kpi.value, x + 3, 13, { bold: true, maxWidth: width - 6 });
      if (kpi.detail) {
        y = top + 14;
        text(kpi.detail, x + 3, 6.5, { color: MUTED, maxWidth: width - 6 });
      }
      y = top;
      if (column === perRow - 1 || index === report.kpis.length - 1) y += height + gap;
    });
    y += 2;
  }

  // Charts: narrow visuals two to a row, wide ones across the page.
  const half = (CONTENT - 4) / 2;
  let pendingRight: { x: number; height: number } | null = null;
  for (const visual of report.visuals) {
    const narrow = visual.width < (report.layoutWidth ?? 900) * 0.62;
    const width = narrow ? half : CONTENT;
    const height = (visual.height / visual.width) * width;
    if (narrow && pendingRight) {
      doc.addImage(visual.dataUrl, 'PNG', pendingRight.x, y, width, height, undefined, 'FAST');
      y += Math.max(pendingRight.height, height) + 4;
      pendingRight = null;
      continue;
    }
    if (pendingRight) {
      y += pendingRight.height + 4;
      pendingRight = null;
    }
    ensure(height + 4);
    doc.addImage(visual.dataUrl, 'PNG', PAGE.margin, y, width, height, undefined, 'FAST');
    if (narrow) pendingRight = { x: PAGE.margin + half + 4, height };
    else y += height + 4;
  }
  if (pendingRight) y += pendingRight.height + 4;

  // Tables. A wide table (a report's records) gets landscape pages of its own, with its columns
  // split across pages when they still do not fit, the first column repeated.
  for (const table of report.tables) {
    const wide = table.columns.length > 7;
    if (wide) {
      doc.addPage('a4', 'landscape');
      y = PAGE.margin;
    } else {
      ensure(20);
    }
    y +=
      text(table.title, PAGE.margin, 11, { bold: true, maxWidth: pageWidth() - PAGE.margin * 2 }) +
      1;
    autoTable(doc, {
      startY: y,
      margin: { left: PAGE.margin, right: PAGE.margin, bottom: PAGE.margin + 8 },
      head: [table.columns.map(String)],
      body: table.rows.map((row) => row.map((cell) => (cell === null ? '—' : String(cell)))),
      styles: {
        fontSize: wide ? 6.5 : 7.5,
        cellPadding: 1.2,
        textColor: [...INK],
        lineColor: [...HAIRLINE],
        lineWidth: 0.1,
        overflow: 'linebreak',
        minCellWidth: wide ? 16 : 10,
      },
      headStyles: { fillColor: [...HEAD_FILL], textColor: [...INK], fontStyle: 'bold' },
      alternateRowStyles: { fillColor: [250, 250, 251] },
      theme: 'grid',
      rowPageBreak: 'avoid',
      horizontalPageBreak: wide,
      ...(wide ? { horizontalPageBreakRepeat: 0 } : {}),
    });
    y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 6;
  }

  // Definitions.
  if (report.notes.length > 0) {
    ensure(16);
    y += text('Definitions and notes', PAGE.margin, 10, { bold: true }) + 1;
    for (const note of report.notes) {
      ensure(8);
      y +=
        text(`• ${note}`, PAGE.margin, 7.5, {
          color: MUTED,
          maxWidth: pageWidth() - PAGE.margin * 2,
        }) + 0.8;
    }
  }

  // Footer on every page.
  const pages = doc.getNumberOfPages();
  for (let page = 1; page <= pages; page += 1) {
    doc.setPage(page);
    const width = pageWidth();
    const height = pageHeight();
    doc.setDrawColor(...HAIRLINE);
    doc.setLineWidth(0.2);
    doc.line(PAGE.margin, height - PAGE.margin - 3, width - PAGE.margin, height - PAGE.margin - 3);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(...MUTED);
    doc.text(`CLIMS · ${report.title}`, PAGE.margin, height - PAGE.margin, { baseline: 'top' });
    doc.text(`Page ${page} of ${pages}`, width - PAGE.margin, height - PAGE.margin, {
      baseline: 'top',
      align: 'right',
    });
  }
  return doc.output('blob');
}

/** The seal at `src` as a data URL for the document header, or null if it cannot be read. */
export async function imageDataUrl(src: string): Promise<string | null> {
  try {
    const blob = await (await fetch(src)).blob();
    return await new Promise((resolve) => {
      const reader = new FileReader();
      reader.onload = () => {
        resolve(typeof reader.result === 'string' ? reader.result : null);
      };
      reader.onerror = () => {
        resolve(null);
      };
      reader.readAsDataURL(blob);
    });
  } catch {
    return null;
  }
}

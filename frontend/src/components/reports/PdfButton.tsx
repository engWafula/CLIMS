'use client';

import { FileDown } from 'lucide-react';
import { useState, type RefObject } from 'react';
import { toast } from 'sonner';

import mohSeal from '@/assets/moh-seal.png';
import { Button } from '@/components/ui/button';
import { Spinner } from '@/components/ui/spinner';
import { useCurrentUser } from '@/features/auth/hooks';
import { downloadName, saveBlob } from '@/lib/export/download';
import type { PdfTable } from '@/lib/export/reportPdf';

interface PdfButtonProps {
  /** The document's title and file name, e.g. "MOH dashboard". */
  title: string;
  subtitle?: string;
  /** The part of the page the document is made from: its figures (`data-kpi`) and charts (`data-visual`). */
  targetRef: RefObject<HTMLElement | null>;
  /** Lines describing what the report covers beyond the filters, e.g. the data time and scope. */
  meta?: readonly (readonly [string, string])[];
  /** Tables to print after the charts, in full rather than one screen page. */
  tables?: readonly PdfTable[] | (() => readonly PdfTable[]);
  /** Definitions printed at the end. */
  notes?: readonly string[];
  disabled?: boolean;
}

/** Reads the figures, charts and filters a page shows, without each page wiring them up. */
function collect(target: HTMLElement) {
  const kpis = [...target.querySelectorAll<HTMLElement>('[data-kpi]')].map((node) => ({
    label: node.dataset.kpiLabel ?? '',
    value: node.dataset.kpiValue ?? '',
    detail: node.dataset.kpiDetail || undefined,
  }));
  const visuals = [...target.querySelectorAll<HTMLElement>('[data-visual]')];
  // Lists that print as tables (a dashboard's watch list), in page order.
  const tables = [...target.querySelectorAll<HTMLElement>('[data-pdf-table]')].flatMap((node) => {
    try {
      return [JSON.parse(node.dataset.pdfTable ?? '') as PdfTable];
    } catch {
      return [];
    }
  });
  const filters: [string, string][] = [];
  const period = document.querySelector<HTMLElement>('[data-filter-period]')?.dataset.filterPeriod;
  if (period) filters.push(['Period', period]);
  const chips = [...document.querySelectorAll<HTMLElement>('[data-filter-chip]')]
    .filter((node) => node.dataset.filterChip !== 'Period')
    .map((node) => `${node.dataset.filterChip}: ${node.dataset.filterValue ?? ''}`);
  filters.push(['Filters', chips.length > 0 ? chips.join(' · ') : 'None (everything you can see)']);
  return { kpis: kpis.filter((kpi) => kpi.value), visuals, filters, tables };
}

/**
 * Downloads the page as a PDF report: header with the ministry's seal, the
 * period and filters, the headline figures, a picture of each chart (in the
 * light theme), any tables, the definitions, and page numbers.
 */
export function PdfButton({
  title,
  subtitle,
  targetRef,
  meta = [],
  tables = [],
  notes = [],
  disabled = false,
}: PdfButtonProps) {
  const user = useCurrentUser();
  const [busy, setBusy] = useState(false);

  const download = async () => {
    const target = targetRef.current;
    if (!target) return;
    setBusy(true);
    try {
      const [{ buildReportPdf, imageDataUrl }, { snapshotElements }] = await Promise.all([
        import('@/lib/export/reportPdf'),
        import('@/lib/export/snapshot'),
      ]);
      const found = collect(target);
      const shots = await snapshotElements(found.visuals);
      const seal = await imageDataUrl(
        typeof mohSeal === 'string' ? mohSeal : (mohSeal as { src: string }).src,
      );
      const generatedAt = new Date();
      const name = user
        ? [user.firstname, user.lastname].filter(Boolean).join(' ') || user.username
        : null;
      const blob = await buildReportPdf({
        title,
        subtitle,
        meta: [...found.filters, ...meta, ...(name ? [['Generated by', name] as const] : [])],
        kpis: found.kpis,
        visuals: shots.map((shot, index) => ({
          ...shot,
          title: found.visuals[index]?.dataset.visualTitle ?? '',
        })),
        tables: [...found.tables, ...(typeof tables === 'function' ? tables() : tables)],
        layoutWidth: target.getBoundingClientRect().width,
        notes,
        seal,
        generatedAt,
      });
      saveBlob(blob, downloadName(title, 'pdf', generatedAt));
      toast.success('PDF report downloaded.');
    } catch (error) {
      console.error('PDF report failed', error);
      toast.error('Could not create the PDF. Try again.');
    } finally {
      setBusy(false);
    }
  };

  return (
    <Button variant="outline" onClick={() => void download()} disabled={disabled || busy}>
      {busy ? (
        <Spinner data-icon="inline-start" aria-hidden="true" />
      ) : (
        <FileDown data-icon="inline-start" />
      )}
      {busy ? 'Preparing PDF…' : 'Download PDF'}
    </Button>
  );
}
